# 1. Load the model from specified path
model_path = "/content/drive/MyDrive/Hakase AI/Ames test/XGboost/1/Genotoxicity-main/model.pkl"
print(f"Loading model from: {model_path}")
with open(model_path, 'rb') as f:
    model = pickle.load(f)

# 2. Define features expected by the model
feature_names = [
    'MinEStateIndex', 'qed', 'MaxAbsPartialCharge', 'MinAbsPartialCharge',
    'BCUT2D_MWHI', 'BCUT2D_MWLOW', 'BCUT2D_MRHI', 'BCUT2D_MRLOW', 'AvgIpc',
    'BalabanJ', 'VSA_EState5', 'ATSC2pe', 'AATSC1c', 'MATS2pe', 'BCUTdv-1h',
    'BCUTs-1h', 'BCUTs-1l', 'BCUTse-1h', 'BCUTse-1l', 'BCUTi-1h', 'BCUTi-1l',
    'RPCG', 'SpMAD_Dt'
]

def calculate_bcut_features(mol):
    res = {}
    for feat in ['BCUT2D_MWHI', 'BCUT2D_MWLOW', 'BCUT2D_MRHI', 'BCUT2D_MRLOW']:
        try:
            res[feat] = getattr(Descriptors, feat)(mol)
        except:
            res[feat] = 0.0
    return res

def get_descriptor_values(smiles):
    mol = Chem.MolFromSmiles(smiles)
    if mol is None:
        return [0.0] * len(feature_names)

    vals = {}
    vals['MinEStateIndex'] = Descriptors.MinEStateIndex(mol)
    vals['qed'] = Descriptors.qed(mol)
    vals['MaxAbsPartialCharge'] = Descriptors.MaxAbsPartialCharge(mol)
    vals['MinAbsPartialCharge'] = Descriptors.MinAbsPartialCharge(mol)

    bcuts = calculate_bcut_features(mol)
    vals.update(bcuts)

    try:
        vals['AvgIpc'] = Descriptors.AvgIpc(mol)
    except:
        vals['AvgIpc'] = 0.0

    vals['BalabanJ'] = Descriptors.BalabanJ(mol)

    try:
        vals['VSA_EState5'] = Descriptors.VSA_EState5(mol)
    except:
        vals['VSA_EState5'] = 0.0

    try:
        vals['ATSC2pe'] = rdMolDescriptors.CalcATSC(mol)[2]
    except:
        vals['ATSC2pe'] = 0.0
    try:
        vals['AATSC1c'] = rdMolDescriptors.CalcAATSC(mol)[1]
    except:
        vals['AATSC1c'] = 0.0
    try:
        vals['MATS2pe'] = rdMolDescriptors.CalcMATS(mol)[2]
    except:
        vals['MATS2pe'] = 0.0

    for f in ['BCUTdv-1h', 'BCUTs-1h', 'BCUTs-1l', 'BCUTse-1h', 'BCUTse-1l', 'BCUTi-1h', 'BCUTi-1l', 'RPCG', 'SpMAD_Dt']:
        try:
            vals[f] = getattr(Descriptors, f.replace('-', '_'))(mol)
        except:
            try:
                vals[f] = getattr(rdMolDescriptors, f)(mol)
            except:
                vals[f] = 0.0

    return [vals.get(f, 0.0) for f in feature_names]

# 3. Load Training Dataset
train_file_path = "/content/drive/MyDrive/Hakase AI/Ames test/XGboost/1/Genotoxicity-main/Dataset/Model Train set/Train set.xlsx"
print(f"Loading training set from: {train_file_path}")
df_train = pd.read_excel(train_file_path)

print("Calculating 23 molecular descriptors...")
X_list = [get_descriptor_values(s) for s in df_train['Smiles']]
X = np.array(X_list)
y = df_train['Labels'].values

# Fallbacks
